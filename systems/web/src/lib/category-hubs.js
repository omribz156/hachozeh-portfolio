export function getCategoryHub(key) {
  const normalized = String(key || '').trim().toLowerCase();
  return PUBLIC_CATEGORY_HUBS.find((category) => category.key === normalized) || null;
}

export function categoryHubPath(key) {
  return `/topics/${encodeURIComponent(key)}`;
}

export function categoryBrowsePath(key) {
  return getCategoryHub(key) ? categoryHubPath(key) : `/?category=${encodeURIComponent(key)}`;
}
